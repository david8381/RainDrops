#!/usr/bin/env node
// Generates docs/Ai/CODE_MAP.md: a compact "symbol -> file:line" index of the
// large runtime files, so an AI assistant (or a human) can jump straight to a
// line range instead of reading thousands of lines to find one function.
//
// Run via `npm run codemap`. The pre-commit hook regenerates and stages it, so
// the line numbers stay honest — do not hand-edit CODE_MAP.md.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8').split('\n');

// Any top-level declaration: `function foo`, `async function foo`, `const foo =`,
// `let foo =`. Column 0 is the whole test — nested declarations are indented.
const DEF_RE = /^(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=/;

/** Top-level definitions as [name, lineNumber]. */
function definitions(lines) {
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const m = DEF_RE.exec(lines[i]);
    if (m) out.push([m[1] || m[2], i + 1]);
  }
  return out;
}

/** Section banners: `// ====` / `// <title>` / `// ====` as [title, startLine]. */
function jsSections(lines) {
  const out = [];
  for (let i = 0; i < lines.length - 2; i++) {
    const isRule = (l) => /^\/\/ ={10,}$/.test(l);
    // The middle line must be a real title, not the opening rule of the next
    // banner (back-to-back banners would otherwise match with a blank title).
    const title = /^\/\/\s*(\S.*)$/.exec(lines[i + 1] ?? '')?.[1]?.trim();
    if (isRule(lines[i]) && isRule(lines[i + 2]) && title && !isRule(lines[i + 1])) {
      out.push([title, i + 1]);
    }
  }
  return out;
}

/** CSS section markers: `/* ── Title ── *​/` as [title, startLine]. */
function cssSections(lines) {
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^\/\*\s*[─-]{2,}\s*(.+?)\s*[─-]{2,}\s*\*\/$/.exec(lines[i]);
    if (m) out.push([m[1], i + 1]);
  }
  return out;
}

/** `name:line, name:line` — one wrapped paragraph, cheapest readable form. */
const compact = (defs) => defs.map(([n, l]) => `${n}:${l}`).join(', ');

/** Split `defs` into the buckets delimited by `sections`. */
function bucket(sections, defs, total) {
  return sections.map(([title, start], i) => {
    const end = i + 1 < sections.length ? sections[i + 1][1] - 1 : total;
    return { title, start, end, defs: defs.filter(([, l]) => l >= start && l <= end) };
  });
}

/** Names inside the trailing `export { … }` block. */
function exportedNames(lines) {
  const start = lines.findIndex((l) => /^export\s*\{/.test(l));
  if (start === -1) return [];
  const names = [];
  for (let i = start + 1; i < lines.length && !/^\}/.test(lines[i]); i++) {
    const name = lines[i].trim().replace(/,$/, '');
    if (/^[A-Za-z_$][\w$]*$/.test(name)) names.push(name);
  }
  return names;
}

const out = [];
const w = (s = '') => out.push(s);

w('# Code Map (generated)');
w();
w('Generated by `npm run codemap` (also run by `.githooks/pre-commit`). **Do not hand-edit.**');
w();
w('A `symbol:line` index of the large runtime files. Use it to read a targeted');
w('range (`Read` with `offset`/`limit`) or to confirm where something belongs,');
w('instead of reading whole files. Line numbers drift between commits — re-run');
w('`npm run codemap` or `grep -n` to confirm before trusting an exact number.');
w();
w('Small files are omitted on purpose: read them whole (`src/curriculum.js`,');
w('`src/engine/*`, `src/audio.js`, `src/text/english.js`, `src/tracks/*`,');
w('`src/types.js`, `src/popups/login-popup.js`, `index.html`).');
w();

// ---- script.js: sections + per-section symbols ----
{
  const lines = read('script.js');
  const secs = bucket(jsSections(lines), definitions(lines), lines.length);
  w(`## script.js (${lines.length} lines)`);
  w();
  w('DOM, canvas, game loop, boss mode, popups. Sections:');
  w();
  for (const s of secs) {
    w(`### ${s.title} — L${s.start}-${s.end}`);
    w();
    w(s.defs.length ? compact(s.defs) : '_(no top-level definitions)_');
    w();
  }
}

// ---- pure modules: exports + all definitions ----
for (const [rel, blurb] of [
  ['src/game-core.js', 'Pure, DOM-free game rules. Unit-tested and type-checked.'],
  ['src/player-progress.js', 'Local profile persistence + readiness. Unit-tested and type-checked.'],
]) {
  const lines = read(rel);
  const defs = definitions(lines);
  const exported = new Set(exportedNames(lines));
  const exportLine = lines.findIndex((l) => /^export\s*\{/.test(l)) + 1;
  w(`## ${rel} (${lines.length} lines)`);
  w();
  w(blurb);
  w();
  w(`All top-level definitions. \`*\` = exported (the \`export {}\` block is at L${exportLine};`);
  w(`${exported.size} of ${defs.length} names are public):`);
  w();
  w(compact(defs.map(([n, l]) => [exported.has(n) ? `${n}*` : n, l])));
  w();
}

// ---- styles.css: sections only ----
{
  const lines = read('styles.css');
  const secs = bucket(cssSections(lines), [], lines.length);
  w(`## styles.css (${lines.length} lines)`);
  w();
  w('Sections (line ranges only — grep for the selector you need):');
  w();
  for (const s of secs) w(`- ${s.title} — L${s.start}-${s.end}`);
  w();
}

writeFileSync(join(ROOT, 'docs/Ai/CODE_MAP.md'), out.join('\n'));
console.log('wrote docs/Ai/CODE_MAP.md');
